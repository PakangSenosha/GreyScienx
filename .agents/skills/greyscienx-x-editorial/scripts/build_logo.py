#!/usr/bin/env python3
"""Build self-contained GreyScienx SVG wordmarks with outlined glyphs."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
from xml.sax.saxutils import escape

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont


WORD = "GREYSCIENX"
SPLIT_AT = 4
CORAL = "#F26157"
LIGHT_FOREGROUND = "#000000"
DARK_FOREGROUND = "#FBFFFE"
CAP_HEIGHT = 72.0
PADDING_X = 4.0
PADDING_Y = 8.0
LETTER_SPACING = -1.7


def outlined_wordmark(font_path: Path, foreground: str, font_hash: str) -> str:
    font = TTFont(font_path)
    cmap = font.getBestCmap()
    glyph_set = font.getGlyphSet()
    hmtx = font["hmtx"].metrics
    units_per_em = font["head"].unitsPerEm
    cap_units = getattr(font.get("OS/2"), "sCapHeight", 0) or units_per_em * 0.72
    scale = CAP_HEIGHT / cap_units

    glyphs: list[tuple[float, str, str]] = []
    cursor = PADDING_X
    for index, character in enumerate(WORD):
        glyph_name = cmap.get(ord(character))
        if glyph_name is None:
            raise ValueError(f"Font does not contain {character!r}")
        pen = SVGPathPen(glyph_set)
        glyph_set[glyph_name].draw(pen)
        fill = foreground if index < SPLIT_AT else CORAL
        glyphs.append((cursor, fill, pen.getCommands()))
        advance = hmtx[glyph_name][0] * scale
        cursor += advance + LETTER_SPACING

    width = cursor - LETTER_SPACING + PADDING_X
    height = CAP_HEIGHT + PADDING_Y * 2
    baseline = PADDING_Y + CAP_HEIGHT
    paths = "\n".join(
        f'  <path fill="{fill}" d="{escape(path_data)}" transform="translate({x:.3f} {baseline:.3f}) scale({scale:.8f} {-scale:.8f})"/>'
        for x, fill, path_data in glyphs
    )
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{width:.3f}" height="{height:.3f}" viewBox="0 0 {width:.3f} {height:.3f}" role="img" aria-labelledby="title desc">
  <title id="title">GreyScienx</title>
  <desc id="desc">GreyScienx outlined wordmark. GREY uses the foreground colour and SCIENX uses coral.</desc>
  <metadata>Generated by scripts/build_logo.py from font SHA-256 {font_hash}. Glyphs are outlined; the SVG has no runtime font dependency.</metadata>
{paths}
</svg>
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", required=True, help="Bold TrueType/OpenType font used to outline the wordmark")
    parser.add_argument("--assets", help="Output assets directory; defaults to the skill assets directory")
    args = parser.parse_args()

    font_path = Path(args.font).expanduser().resolve()
    if not font_path.is_file():
        raise FileNotFoundError(font_path)
    assets = Path(args.assets).expanduser().resolve() if args.assets else Path(__file__).resolve().parents[1] / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    font_hash = hashlib.sha256(font_path.read_bytes()).hexdigest()

    outputs = {
        assets / "greyscienx-logo.svg": outlined_wordmark(font_path, LIGHT_FOREGROUND, font_hash),
        assets / "greyscienx-logo-inverse.svg": outlined_wordmark(font_path, DARK_FOREGROUND, font_hash),
    }
    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8", newline="\n")
        print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
